public class TrimOrchestrator
{
    public const string TrimmedSuffix = "-trimmed.mzML";
    public const string PeakDataFileSuffix = "-ms1Data.csv";
    public const string? OutputDirectory = "Trimmed-2";
    public const string? TICDir = "ExtractedMetrics";

    public static void TrimFilesInDirectory(string directoryPath, double trimStartRT = 0.0, double trimEndRT = double.MaxValue)
    {
        var files = Directory.GetFiles(directoryPath, "*.raw", SearchOption.TopDirectoryOnly);
        var expDesignPath = Path.Combine(directoryPath, "ExperimentalDesign.tsv");
        bool designExists = File.Exists(expDesignPath);
        var designRecords = designExists ? ReadExperimentalDesign(expDesignPath) : new List<ExperimentalDesignRecord>();

        foreach (var file in files)
        {
            if (file.Contains("blank", StringComparison.OrdinalIgnoreCase))
                continue;

            var trimmer = new DataFileTrimmer(file, trimStartRT, trimEndRT);
            var newDataFile = trimmer.Trim(out int trimmedMs1Count, out int trimmedMs2Count);
            var newFilePath = GetOutPath(file, true);

            if (designExists)
                UpdateExperimentalDesignInPlace(newFilePath, designRecords);

            newDataFile.ExportAsMzML(newFilePath, writeIndexed: false);
        }

        if (designExists)
            WriteExperimentalDesign(expDesignPath, designRecords);
    }

    public static void MakeMs1TicFile(string rawFilePath, string? outputDirectory = null)
    {
        var dataFile = MsDataFileReader.GetDataFile(rawFilePath);
        var ms1Scans = dataFile.GetAllScansList().Where(p => p.MsnOrder == 1).ToList();
        var ticData = ms1Scans.Select(p => new { ScanNumber = p.OneBasedScanNumber, RetentionTime = p.RetentionTime, TIC = p.TotalIonCurrent }).ToList();

        var outDir = outputDirectory ?? Path.Combine(Path.GetDirectoryName(rawFilePath), TICDir);
        Directory.CreateDirectory(outDir);

        var outputFileName = Path.Combine(outDir, Path.GetFileNameWithoutExtension(rawFilePath) + "-ms1TIC.csv");
        using (var writer = new StreamWriter(outputFileName))
        {
            writer.WriteLine("ScanNumber,RetentionTime,TIC");
            foreach (var entry in ticData)
            {
                writer.WriteLine(string.Join(",",
                    entry.ScanNumber.ToString(CultureInfo.InvariantCulture),
                    entry.RetentionTime.ToString("R", CultureInfo.InvariantCulture),
                    entry.TIC.ToString("R", CultureInfo.InvariantCulture)));
            }
        }
    }

    public static List<Ms1XicTarget> ReadMs1XicTargets(string targetPath)
    {
        using var reader = new StreamReader(targetPath);
        using var csv = new CsvHelper.CsvReader(
            reader,
            new CsvConfiguration(CultureInfo.InvariantCulture) { Delimiter = "\t" });
        var targets = csv.GetRecords<Ms1XicTarget>().ToList();
        if (targets.Count == 0)
            throw new InvalidDataException($"No XIC targets found in {targetPath}.");
        if (targets.Any(target => string.IsNullOrWhiteSpace(target.TargetId) || target.MZ <= 0 || target.PPM <= 0))
            throw new InvalidDataException($"Invalid XIC target in {targetPath}.");
        if (targets.Select(target => target.TargetId).Distinct(StringComparer.Ordinal).Count() != targets.Count)
            throw new InvalidDataException($"XIC target IDs must be unique in {targetPath}.");
        return targets;
    }

    public static void MakeMs1XicFile(
        string rawFilePath,
        IReadOnlyList<Ms1XicTarget> targets,
        string outputDirectory)
    {
        var dataFile = MsDataFileReader.GetDataFile(rawFilePath);
        dataFile.LoadAllStaticData();
        var ms1Scans = dataFile.GetAllScansList()
            .Where(scan => scan.MsnOrder == 1 && scan.Polarity == Polarity.Negative)
            .ToList();
        if (ms1Scans.Count == 0)
            throw new InvalidDataException($"No negative-polarity MS1 scans found in {rawFilePath}.");

        Directory.CreateDirectory(outputDirectory);
        var outputPath = Path.Combine(
            outputDirectory,
            Path.GetFileNameWithoutExtension(rawFilePath) + "-ms1XIC.csv");
        using var writer = new StreamWriter(outputPath);
        writer.WriteLine("ScanNumber,RetentionTime,TargetId,TargetMZ,Charge,XIC");
        foreach (var scan in ms1Scans)
        {
            foreach (var target in targets)
            {
                var xic = SumIntensityWithinPpm(scan.MassSpectrum, target.MZ, target.PPM);
                writer.WriteLine(string.Join(",",
                    scan.OneBasedScanNumber.ToString(CultureInfo.InvariantCulture),
                    scan.RetentionTime.ToString("R", CultureInfo.InvariantCulture),
                    target.TargetId,
                    target.MZ.ToString("R", CultureInfo.InvariantCulture),
                    target.Charge.ToString(CultureInfo.InvariantCulture),
                    xic.ToString("R", CultureInfo.InvariantCulture)));
            }
        }
    }

    private static double SumIntensityWithinPpm(MzSpectrum spectrum, double mz, double ppm)
    {
        var masses = spectrum.XArray;
        var intensities = spectrum.YArray;
        var tolerance = mz * ppm / 1_000_000;
        var start = LowerBound(masses, mz - tolerance);
        var end = UpperBound(masses, mz + tolerance);
        double total = 0;
        for (var index = start; index < end; index++)
            total += intensities[index];
        return total;
    }

    private static int LowerBound(double[] sortedValues, double value)
    {
        var low = 0;
        var high = sortedValues.Length;
        while (low < high)
        {
            var middle = low + (high - low) / 2;
            if (sortedValues[middle] < value)
                low = middle + 1;
            else
                high = middle;
        }
        return low;
    }

    private static int UpperBound(double[] sortedValues, double value)
    {
        var low = 0;
        var high = sortedValues.Length;
        while (low < high)
        {
            var middle = low + (high - low) / 2;
            if (sortedValues[middle] <= value)
                low = middle + 1;
            else
                high = middle;
        }
        return low;
    }

    public static string GetOutPath(string inPath, bool rawFile)
    {
        var withoutExtension = Path.Combine(Path.GetDirectoryName(inPath) ?? "", Path.GetFileNameWithoutExtension(inPath));

        // Create new directory if not present. 
        if (OutputDirectory != null)
        {
            var outDir = Path.Combine(Path.GetDirectoryName(inPath) ?? "", OutputDirectory);
            if (!Directory.Exists(outDir))
                Directory.CreateDirectory(outDir);
            withoutExtension = Path.Combine(outDir, Path.GetFileNameWithoutExtension(inPath));
        }

        return withoutExtension + (rawFile ? TrimmedSuffix : PeakDataFileSuffix);
    }

    public static void UpdateExperimentalDesignInPlace(string newSpectraPath, List<ExperimentalDesignRecord> existingRecords)
    {
        var newFileName = Path.GetFileName(newSpectraPath);
        foreach (var record in existingRecords)
        {
            if (newFileName.Contains(record.FileName, StringComparison.OrdinalIgnoreCase))
            {
                record.FileName = newFileName;
                break;
            }
        }
    }

    public static List<ExperimentalDesignRecord> ReadExperimentalDesign(string expDesignPath)
    {
        if (!File.Exists(expDesignPath))
            throw new FileNotFoundException($"Experimental design file not found: {expDesignPath}");
        using var reader = new StreamReader(expDesignPath);
        using var csv = new CsvHelper.CsvReader(reader, ExperimentalDesignRecord.Configuration);
        var records = csv.GetRecords<ExperimentalDesignRecord>().ToList();
        return records;
    }

    public static void WriteExperimentalDesign(string expDesignPath, List<ExperimentalDesignRecord> records)
    {
        using var writer = new StreamWriter(expDesignPath);
        using var csv = new CsvHelper.CsvWriter(writer, ExperimentalDesignRecord.Configuration);
        csv.WriteHeader<ExperimentalDesignRecord>();
        csv.NextRecord();
        foreach (var record in records)
        {
            csv.WriteRecord(record);
            csv.NextRecord();
        }
    }


}

