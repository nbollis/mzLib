public class DataFileTrimmer
{


    public MsDataFile DataFile { get; init; }

    public double RollingAverage { get; set; } = 3;
    public double MinPeeksToKeep { get; set; } = 101;
    public double MinMs2ToKeep { get; set; } = 1;
    public double TrimStartRT { get; set; }
    public double TrimEndRT { get; set; }

    public DataFileTrimmer(string filePath, double trimStartRT = 0.0, double trimEndRT = double.MaxValue)
    {
        DataFile = MsDataFileReader.GetDataFile(filePath);
        TrimStartRT = trimStartRT;
        TrimEndRT = trimEndRT;
    }

    public void TrimAndExport()
    {
        var newFile = Trim(out _, out _);
        newFile.ExportAsMzML(TrimOrchestrator.GetOutPath(DataFile.FilePath, true), writeIndexed: false);
    }

    public MsDataFile Trim(out int trimmed1, out int trimmed2)
    {
        trimmed1 = 0;
        trimmed2 = 0;
        DataFile.LoadAllStaticData();
        var originalScans = DataFile.GetAllScansList();

        List<ScanData> scanDataList = new();
        Dictionary<int, int> Ms1ScanNumberToMs2Count = new();
        Dictionary<int, List<int>> OriginalMs1ToMs2ScanNumbers = new();
        var allMs1Tics = originalScans.Where(p => p.MsnOrder == 1).Select(p => p.TotalIonCurrent).ToList();
        var allMs1InjectionTimes = originalScans.Where(p => p.MsnOrder == 1).Select(p => p.InjectionTime.Value).ToList();
        var allPeakCount = originalScans.Where(p => p.MsnOrder == 1).Select(p => p.MassSpectrum.XArray.Length).ToList();

        var ms1Scans = originalScans.Where(p => p.MsnOrder == 1).ToList();
        var ms2Scans = originalScans.Where(p => p.MsnOrder == 2).ToList();


        // Aggregate Metrics
        for (int i = 0; i < ms1Scans.Count; i++)
        {
            var scan = ms1Scans[i];
            var ticWindow = allMs1Tics.Skip(Math.Max(0, i - (int)(RollingAverage / 2))).Take((int)RollingAverage).ToList();
            var injectionTimeWindow = allMs1InjectionTimes.Skip(Math.Max(0, i - (int)(RollingAverage / 2))).Take((int)RollingAverage).ToList();
            var peakCountWindow = allPeakCount.Skip(Math.Max(0, i - (int)(RollingAverage / 2))).Take((int)RollingAverage).ToList();
            double rollingTIC = ticWindow.Average();
            double rollingInjectionTime = injectionTimeWindow.Average();
            double rollingPeakCount = peakCountWindow.Average();

            scanDataList.Add(new ScanData
            {
                ScanNumber = scan.OneBasedScanNumber,
                RetentionTime = scan.RetentionTime,
                TIC = scan.TotalIonCurrent,
                RollingTIC = rollingTIC,
                PeakCount = scan.MassSpectrum.XArray.Length,
                RollingPeakCount = rollingPeakCount,
                Ms2Count = 0,
                InjectionTime = scan.InjectionTime.Value,
                RollingInjectionTime = rollingInjectionTime
            });
        }

        for (int i = 0; i < ms2Scans.Count; i++)
        {
            var scan = ms2Scans[i];
            if (scan.OneBasedPrecursorScanNumber > 0 && scan.OneBasedPrecursorScanNumber <= DataFile.NumSpectra)
            {
                if (!Ms1ScanNumberToMs2Count.ContainsKey(scan.OneBasedPrecursorScanNumber.Value))
                    Ms1ScanNumberToMs2Count[scan.OneBasedPrecursorScanNumber.Value] = 0;
                Ms1ScanNumberToMs2Count[scan.OneBasedPrecursorScanNumber.Value]++;
                if (!OriginalMs1ToMs2ScanNumbers.ContainsKey(scan.OneBasedPrecursorScanNumber.Value))
                    OriginalMs1ToMs2ScanNumbers[scan.OneBasedPrecursorScanNumber.Value] = new List<int>();
                OriginalMs1ToMs2ScanNumbers[scan.OneBasedPrecursorScanNumber.Value].Add(scan.OneBasedScanNumber);
            }
            else
            {
                Console.WriteLine($"Warning: Scan {scan.OneBasedScanNumber} has an invalid precursor scan number {scan.OneBasedPrecursorScanNumber}. Skipping this scan.");
                continue;
            }
        }

        for (int i = 0; i < scanDataList.Count; i++)
        {
            var scanData = scanDataList[i];
            if (Ms1ScanNumberToMs2Count.TryGetValue(scanData.ScanNumber, out int ms2Count))
            {
                scanData.Ms2Count = ms2Count;
            }
        }

        var dataOutPath = TrimOrchestrator.GetOutPath(DataFile.FilePath, false).Replace(".raw", "");
        var scanDataFile = new ScanDataFile
        {
            FilePath = dataOutPath,
            Results = scanDataList
        };
        scanDataFile.WriteResults(dataOutPath);
        scanDataFile.BuildDictionary();

        // Do Trimming
        List<MsDataScan> trimmedScans = new(DataFile.NumSpectra);
        Dictionary<int, int> originalMs1ScanNumberToAdjusted = new();
        int runningScanNumber = 0;
        int lastMs1ScanNumber = 0;
        foreach (var scan in originalScans)
        {
            // Before the start of our trimming time - Add them all - No need to adjust numbers
            if (scan.RetentionTime < TrimStartRT)
            {
                runningScanNumber++;
                if (scan.MsnOrder == 1)
                {
                    originalMs1ScanNumberToAdjusted.Add(scan.OneBasedScanNumber, runningScanNumber);
                    lastMs1ScanNumber = scan.OneBasedScanNumber;
                }
                trimmedScans.Add(scan);
            }
            // After the end of our trimming time - Add them all - Adjust numbers
            else if (scan.RetentionTime > TrimEndRT)
            {
                if (scan.MsnOrder == 1)
                {
                    runningScanNumber++;

                    originalMs1ScanNumberToAdjusted.Add(scan.OneBasedScanNumber, runningScanNumber);
                    scan.SetNativeID(scan.NativeId.Replace($"scan={scan.OneBasedScanNumber}", $"scan={runningScanNumber}"));
                    scan.SetOneBasedScanNumber(runningScanNumber);

                    lastMs1ScanNumber = scan.OneBasedScanNumber;
                    trimmedScans.Add(scan);
                }
                else
                {
                    runningScanNumber++;
                    var ms1ScanNumber = lastMs1ScanNumber;
                    if (originalMs1ScanNumberToAdjusted.TryGetValue(scan.OneBasedPrecursorScanNumber.Value, out var adjustedMs1ScanNumber))
                        ms1ScanNumber = adjustedMs1ScanNumber;

                    scan.SetNativeID(scan.NativeId.Replace($"scan={scan.OneBasedScanNumber}", $"scan={runningScanNumber}"));
                    scan.SetOneBasedScanNumber(runningScanNumber);
                    scan.SetOneBasedPrecursorScanNumber(ms1ScanNumber);
                    trimmedScans.Add(scan);
                }
            }
            // In Trim Range - Apply filtering criteria
            else if (scan.MsnOrder == 1)
            {
                var scanData = scanDataFile.ScanNumberToData[scan.OneBasedScanNumber];

                // meets filtering criteria, keep it
                if (scanData.Ms2Count >= MinMs2ToKeep
                    && scanData.PeakCount >= MinPeeksToKeep
                    && scanData.TIC >= scanData.RollingTIC * 0.1
                    && scanData.InjectionTime >= scanData.RollingInjectionTime * 0.1
                    && scanData.PeakCount >= scanData.RollingPeakCount * 0.1)
                {
                    runningScanNumber++;
                    originalMs1ScanNumberToAdjusted.Add(scan.OneBasedScanNumber, runningScanNumber);
                    scan.SetNativeID(scan.NativeId.Replace($"scan={scan.OneBasedScanNumber}", $"scan={runningScanNumber}"));
                    scan.SetOneBasedScanNumber(runningScanNumber);

                    lastMs1ScanNumber = scan.OneBasedScanNumber;
                    trimmedScans.Add(scan);
                }
                else
                {
                    trimmed1++;
                }
            }
            // MS2 scans - Adjust numbers based on the adjusted MS1 scan number - Retain All
            else if (scan.MsnOrder == 2)
            {
                var ms1ScanNumber = lastMs1ScanNumber;

                if (originalMs1ScanNumberToAdjusted.TryGetValue(scan.OneBasedPrecursorScanNumber.Value, out var adjustedMs1ScanNumber))
                    ms1ScanNumber = adjustedMs1ScanNumber;

                runningScanNumber++;

                scan.SetNativeID(scan.NativeId.Replace($"scan={scan.OneBasedScanNumber}", $"scan={runningScanNumber}"));
                scan.SetOneBasedScanNumber(runningScanNumber);
                scan.SetOneBasedPrecursorScanNumber(ms1ScanNumber);

                trimmedScans.Add(scan);
            }
        }

        var source = (SourceFile)DataFile.SourceFile.Clone();
        var newFile = new GenericMsDataFile(trimmedScans.ToArray(), source);
        return newFile;
    }


}

public class ScanData : IEquatable<ScanData>
{
    public static CsvConfiguration Configuration = new CsvConfiguration(System.Globalization.CultureInfo.InvariantCulture)
    {
        HasHeaderRecord = true,
        Delimiter = ",",
    };

    public int ScanNumber { get; set; }
    public double RetentionTime { get; set; }
    public double TIC { get; set; }
    public double RollingTIC { get; set; }
    public int PeakCount { get; set; }
    public double RollingPeakCount { get; set; }
    public int Ms2Count { get; set; }
    public double InjectionTime { get; set; }
    public double RollingInjectionTime { get; set; }

    public bool Equals(ScanData? other)
    {
        if (other == null) return false;
        return ScanNumber == other.ScanNumber &&
               RetentionTime == other.RetentionTime &&
               TIC == other.TIC &&
               PeakCount == other.PeakCount &&
               Ms2Count == other.Ms2Count;
    }
}

public class ScanDataFile : ResultFile<ScanData>, IResultFile
{
    public override SupportedFileType FileType => throw new NotImplementedException();

    public override Software Software { get; set; }

    public Dictionary<int, ScanData> ScanNumberToData { get; set; } = new Dictionary<int, ScanData>();

    public void BuildDictionary()
    {
        ScanNumberToData = Results.ToDictionary(x => x.ScanNumber, x => x);
    }

    public override void LoadResults()
    {
        using var csvHelper = new CsvHelper.CsvReader(new StreamReader(FilePath), ScanData.Configuration);

        var loaded = csvHelper.GetRecords<ScanData>().ToList();
        Results = loaded;
    }


    public override void WriteResults(string outputPath)
    {
        using var helper = new CsvHelper.CsvWriter(new StreamWriter(outputPath), ScanData.Configuration);
        helper.WriteHeader<ScanData>();
        helper.NextRecord();
        foreach (var result in Results)
        {
            helper.WriteRecord(result);
            helper.NextRecord();
        }
    }
}

